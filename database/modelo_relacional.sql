-- LEITURA
--------------------
CREATE TABLE LEITURA (
    ID_LEITURA      NUMBER(12)   NOT NULL,
    ID_ESCADA       NUMBER(10)   NOT NULL,
    DT_LEITURA      TIMESTAMP    NOT NULL,
    VL_VIBRACAO     NUMBER(6,2)  NOT NULL,
    VL_TEMPERATURA  NUMBER(5,2)  NOT NULL,
    VL_CORRENTE     NUMBER(6,2)  NOT NULL,
    VL_TENSAO       NUMBER(6,2)  NOT NULL,
    VL_NIVEL_OLEO   NUMBER(5,2)  NOT NULL,
    VL_VELOCIDADE   NUMBER(5,3)  NOT NULL
);

ALTER TABLE LEITURA ADD CONSTRAINT PK_LEITURA PRIMARY KEY (ID_LEITURA);
ALTER TABLE LEITURA ADD CONSTRAINT UK_LEITURA_ESCADA_DATA UNIQUE (ID_ESCADA, DT_LEITURA);
ALTER TABLE LEITURA ADD CONSTRAINT FK_LEITURA_ESCADA
    FOREIGN KEY (ID_ESCADA) REFERENCES ESCADA_ROLANTE (ID_ESCADA);
ALTER TABLE LEITURA ADD CONSTRAINT CK_LEITURA_VIBRACAO    CHECK (VL_VIBRACAO BETWEEN 0 AND 100);
ALTER TABLE LEITURA ADD CONSTRAINT CK_LEITURA_TEMPERATURA CHECK (VL_TEMPERATURA BETWEEN -20 AND 150);
ALTER TABLE LEITURA ADD CONSTRAINT CK_LEITURA_CORRENTE    CHECK (VL_CORRENTE BETWEEN 0 AND 200);
ALTER TABLE LEITURA ADD CONSTRAINT CK_LEITURA_TENSAO      CHECK (VL_TENSAO BETWEEN 0 AND 500);
ALTER TABLE LEITURA ADD CONSTRAINT CK_LEITURA_NIVEL_OLEO  CHECK (VL_NIVEL_OLEO BETWEEN 0 AND 100);
ALTER TABLE LEITURA ADD CONSTRAINT CK_LEITURA_VELOCIDADE  CHECK (VL_VELOCIDADE BETWEEN 0 AND 2);

COMMENT ON TABLE  LEITURA                IS 'Registro dos seis sinais de uma escada em um instante. Equivale a uma linha do dataset da Motiva ou a uma mensagem do ESP32.';
COMMENT ON COLUMN LEITURA.ID_LEITURA     IS 'Identificador da leitura (chave primária).';
COMMENT ON COLUMN LEITURA.ID_ESCADA      IS 'Escada que gerou a leitura (chave estrangeira).';
COMMENT ON COLUMN LEITURA.DT_LEITURA     IS 'Instante da medição. Única por escada, para barrar leituras duplicadas.';
COMMENT ON COLUMN LEITURA.VL_VIBRACAO    IS 'Vibração do motor/redutor em mm/s.';
COMMENT ON COLUMN LEITURA.VL_TEMPERATURA IS 'Temperatura dos componentes mecânicos em °C.';
COMMENT ON COLUMN LEITURA.VL_CORRENTE    IS 'Corrente do motor em A.';
COMMENT ON COLUMN LEITURA.VL_TENSAO      IS 'Tensão de alimentação em V.';
COMMENT ON COLUMN LEITURA.VL_NIVEL_OLEO  IS 'Nível do reservatório de óleo do redutor em %.';
COMMENT ON COLUMN LEITURA.VL_VELOCIDADE  IS 'Velocidade real dos degraus em m/s.';

