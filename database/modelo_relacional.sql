-- DISPOSITIVO_IOT
-- --------------------
CREATE TABLE DISPOSITIVO_IOT (
    ID_DISPOSITIVO         NUMBER(10)    NOT NULL,
    ID_ESCADA              NUMBER(10)    NOT NULL,
    CD_MAC                 VARCHAR2(17)  NOT NULL,
    DS_MODELO              VARCHAR2(40)  NOT NULL,
    DS_FIRMWARE            VARCHAR2(15)  NOT NULL,
    DT_ULTIMA_COMUNICACAO  TIMESTAMP,
    FL_ATIVO               CHAR(1)       DEFAULT 'S' NOT NULL
);

ALTER TABLE DISPOSITIVO_IOT ADD CONSTRAINT PK_DISPOSITIVO_IOT PRIMARY KEY (ID_DISPOSITIVO);
ALTER TABLE DISPOSITIVO_IOT ADD CONSTRAINT UK_DISPOSITIVO_MAC UNIQUE (CD_MAC);
ALTER TABLE DISPOSITIVO_IOT ADD CONSTRAINT FK_DISPOSITIVO_ESCADA
    FOREIGN KEY (ID_ESCADA) REFERENCES ESCADA_ROLANTE (ID_ESCADA);
ALTER TABLE DISPOSITIVO_IOT ADD CONSTRAINT CK_DISPOSITIVO_MAC
    CHECK (REGEXP_LIKE(CD_MAC, '^([0-9A-F]{2}:){5}[0-9A-F]{2}$'));
ALTER TABLE DISPOSITIVO_IOT ADD CONSTRAINT CK_DISPOSITIVO_FIRMWARE
    CHECK (REGEXP_LIKE(DS_FIRMWARE, '^[0-9]+\.[0-9]+\.[0-9]+$'));
ALTER TABLE DISPOSITIVO_IOT ADD CONSTRAINT CK_DISPOSITIVO_ATIVO
    CHECK (FL_ATIVO IN ('S', 'N'));

COMMENT ON TABLE  DISPOSITIVO_IOT                       IS 'Dispositivo IoT (ESP32) instalado em uma escada. Apenas lê e envia dados; nunca comanda a escada.';
COMMENT ON COLUMN DISPOSITIVO_IOT.ID_DISPOSITIVO        IS 'Identificador do dispositivo (chave primária).';
COMMENT ON COLUMN DISPOSITIVO_IOT.ID_ESCADA             IS 'Escada monitorada pelo dispositivo (chave estrangeira).';
COMMENT ON COLUMN DISPOSITIVO_IOT.CD_MAC                IS 'Endereço MAC no formato AA:BB:CC:DD:EE:FF (Value Object EnderecoMac).';
COMMENT ON COLUMN DISPOSITIVO_IOT.DS_MODELO             IS 'Modelo da placa, ex.: ESP32-WROOM-32.';
COMMENT ON COLUMN DISPOSITIVO_IOT.DS_FIRMWARE           IS 'Versão do firmware no formato 1.0.0.';
COMMENT ON COLUMN DISPOSITIVO_IOT.DT_ULTIMA_COMUNICACAO IS 'Instante da última mensagem recebida; usado para saber se está online.';
COMMENT ON COLUMN DISPOSITIVO_IOT.FL_ATIVO              IS 'S = em operação; N = retirado (troca ou manutenção).';

