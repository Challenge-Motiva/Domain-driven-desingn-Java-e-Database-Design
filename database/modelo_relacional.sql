-- ALERTA
--------------------
CREATE TABLE ALERTA (
    ID_ALERTA         NUMBER(12)    NOT NULL,
    ID_LEITURA        NUMBER(12)    NOT NULL,
    DS_SINAL          VARCHAR2(15)  NOT NULL,
    VL_MEDIDO         NUMBER(8,3)   NOT NULL,
    VL_LIMITE         NUMBER(8,3)   NOT NULL,
    DS_NIVEL          VARCHAR2(10)  NOT NULL,
    ST_ALERTA         VARCHAR2(10)  DEFAULT 'ABERTO' NOT NULL,
    DT_ABERTURA       TIMESTAMP     NOT NULL,
    NM_DECIDIDO_POR   VARCHAR2(80),
    DS_JUSTIFICATIVA  VARCHAR2(500),
    DT_DECISAO        TIMESTAMP
);

ALTER TABLE ALERTA ADD CONSTRAINT PK_ALERTA PRIMARY KEY (ID_ALERTA);
ALTER TABLE ALERTA ADD CONSTRAINT UK_ALERTA_LEITURA_SINAL UNIQUE (ID_LEITURA, DS_SINAL);
ALTER TABLE ALERTA ADD CONSTRAINT FK_ALERTA_LEITURA
    FOREIGN KEY (ID_LEITURA) REFERENCES LEITURA (ID_LEITURA);
ALTER TABLE ALERTA ADD CONSTRAINT CK_ALERTA_SINAL
    CHECK (DS_SINAL IN ('VIBRACAO', 'TEMPERATURA', 'CORRENTE', 'TENSAO', 'NIVEL_OLEO', 'VELOCIDADE'));
ALTER TABLE ALERTA ADD CONSTRAINT CK_ALERTA_NIVEL
    CHECK (DS_NIVEL IN ('ATENCAO', 'CRITICO'));
ALTER TABLE ALERTA ADD CONSTRAINT CK_ALERTA_STATUS
    CHECK (ST_ALERTA IN ('ABERTO', 'CONFIRMADO', 'DESCARTADO'));
ALTER TABLE ALERTA ADD CONSTRAINT CK_ALERTA_JUSTIFICATIVA
    CHECK (DS_JUSTIFICATIVA IS NULL OR LENGTH(TRIM(DS_JUSTIFICATIVA)) >= 10);
ALTER TABLE ALERTA ADD CONSTRAINT CK_ALERTA_DECISAO
    CHECK ((ST_ALERTA = 'ABERTO'
            AND NM_DECIDIDO_POR IS NULL AND DS_JUSTIFICATIVA IS NULL AND DT_DECISAO IS NULL)
        OR (ST_ALERTA IN ('CONFIRMADO', 'DESCARTADO')
            AND NM_DECIDIDO_POR IS NOT NULL AND DS_JUSTIFICATIVA IS NOT NULL AND DT_DECISAO IS NOT NULL));
ALTER TABLE ALERTA ADD CONSTRAINT CK_ALERTA_DATAS
    CHECK (DT_DECISAO IS NULL OR DT_DECISAO >= DT_ABERTURA);

COMMENT ON TABLE  ALERTA                  IS 'Aviso de que um sinal ultrapassou o limite. Guarda a evidência e a decisão do gestor (rastreabilidade).';
COMMENT ON COLUMN ALERTA.ID_ALERTA        IS 'Identificador do alerta (chave primária).';
COMMENT ON COLUMN ALERTA.ID_LEITURA       IS 'Leitura que disparou o alerta (chave estrangeira). A escada é obtida pela leitura.';
COMMENT ON COLUMN ALERTA.DS_SINAL         IS 'Sinal que ultrapassou o limite (enum TipoSinal).';
COMMENT ON COLUMN ALERTA.VL_MEDIDO        IS 'Valor medido do sinal, copiado da leitura como evidência.';
COMMENT ON COLUMN ALERTA.VL_LIMITE        IS 'Limite ultrapassado no momento do alerta; preservado mesmo se os limites mudarem depois.';
COMMENT ON COLUMN ALERTA.DS_NIVEL         IS 'Gravidade: ATENCAO ou CRITICO (enum NivelAlerta).';
COMMENT ON COLUMN ALERTA.ST_ALERTA        IS 'ABERTO até o gestor decidir; depois CONFIRMADO ou DESCARTADO (enum StatusAlerta).';
COMMENT ON COLUMN ALERTA.DT_ABERTURA      IS 'Instante de abertura do alerta (igual ao da leitura de origem).';
COMMENT ON COLUMN ALERTA.NM_DECIDIDO_POR  IS 'Gestor que confirmou ou descartou; obrigatório após a decisão.';
COMMENT ON COLUMN ALERTA.DS_JUSTIFICATIVA IS 'Motivo da decisão, de 10 a 500 caracteres (Value Object Justificativa).';
COMMENT ON COLUMN ALERTA.DT_DECISAO       IS 'Instante da decisão; não pode ser anterior à abertura.';

