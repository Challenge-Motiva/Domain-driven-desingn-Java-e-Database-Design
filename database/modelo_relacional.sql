-- --------------------
-- Monitoramento de Escadas Rolantes — Challenge FIAP + Motiva 2026
-- Modelo relacional (Oracle) — Sprint 1/2 de Database Design
--
-- Compatível com o modelo de classes de DDD Java:
--   Estacao → ESTACAO            EscadaRolante → ESCADA_ROLANTE
--   DispositivoIoT → DISPOSITIVO_IOT    Leitura → LEITURA
--   Alerta → ALERTA              Equipe → EQUIPE
--   OrdemServico → ORDEM_SERVICO
--
-- Convenção de nomes das colunas:
--   ID_ identificador   NM_ nome      SG_ sigla       CD_ código
--   DS_ descrição       ST_ status    DT_ data/hora   VL_ valor medido
--   QT_ quantidade      FL_ indicador S/N
--
-- Enumerações do Java são gravadas pelo nome da constante (ex.: 'CRITICA_A')
-- e protegidas por CHECK. Value Objects viram colunas da própria tabela.
-- Faixas de valores físicos e limites são PROVISÓRIOS até a análise do dataset.
-- --------------------

-- -----------------
-- ESTACAO
--------------------
CREATE TABLE ESTACAO (
    ID_ESTACAO      NUMBER(10)    NOT NULL,
    NM_ESTACAO      VARCHAR2(80)  NOT NULL,
    SG_ESTACAO      CHAR(3)       NOT NULL,
    DS_LINHA        VARCHAR2(20)  NOT NULL
);

ALTER TABLE ESTACAO ADD CONSTRAINT PK_ESTACAO PRIMARY KEY (ID_ESTACAO);
ALTER TABLE ESTACAO ADD CONSTRAINT UK_ESTACAO_SIGLA UNIQUE (SG_ESTACAO);
ALTER TABLE ESTACAO ADD CONSTRAINT CK_ESTACAO_SIGLA
    CHECK (REGEXP_LIKE(SG_ESTACAO, '^[A-Z]{3}$'));
ALTER TABLE ESTACAO ADD CONSTRAINT CK_ESTACAO_LINHA
    CHECK (DS_LINHA IN ('LINHA_4_AMARELA', 'LINHA_5_LILAS', 'LINHA_8_DIAMANTE', 'LINHA_9_ESMERALDA'));

COMMENT ON TABLE  ESTACAO            IS 'Estação onde as escadas rolantes estão instaladas. Agrupa as escadas no dashboard e serve de base para as equipes.';
COMMENT ON COLUMN ESTACAO.ID_ESTACAO IS 'Identificador da estação (chave primária).';
COMMENT ON COLUMN ESTACAO.NM_ESTACAO IS 'Nome da estação, ex.: Paulista.';
COMMENT ON COLUMN ESTACAO.SG_ESTACAO IS 'Sigla de 3 letras usada no código das escadas, ex.: PAU.';
COMMENT ON COLUMN ESTACAO.DS_LINHA   IS 'Linha operada pela Motiva à qual a estação pertence (enum Linha).';

--------------------
--ESCADA_ROLANTE
--------------------
CREATE TABLE ESCADA_ROLANTE (
    ID_ESCADA            NUMBER(10)    NOT NULL,
    ID_ESTACAO           NUMBER(10)    NOT NULL,
    CD_ESCADA            VARCHAR2(10)  NOT NULL,
    DS_GRUPO_MANUTENCAO  VARCHAR2(15)  NOT NULL,
    DS_FABRICANTE        VARCHAR2(15)  NOT NULL,
    DS_ACESSO            VARCHAR2(100) NOT NULL,
    ST_CONDICAO          VARCHAR2(25)  DEFAULT 'SEM_DADOS' NOT NULL,
    DT_ULTIMA_LEITURA    TIMESTAMP
);

ALTER TABLE ESCADA_ROLANTE ADD CONSTRAINT PK_ESCADA_ROLANTE PRIMARY KEY (ID_ESCADA);
ALTER TABLE ESCADA_ROLANTE ADD CONSTRAINT UK_ESCADA_CODIGO UNIQUE (CD_ESCADA);
ALTER TABLE ESCADA_ROLANTE ADD CONSTRAINT FK_ESCADA_ESTACAO
    FOREIGN KEY (ID_ESTACAO) REFERENCES ESTACAO (ID_ESTACAO);
ALTER TABLE ESCADA_ROLANTE ADD CONSTRAINT CK_ESCADA_CODIGO
    CHECK (REGEXP_LIKE(CD_ESCADA, '^ECR-[A-Z]{3}-[0-9]{2}$'));
ALTER TABLE ESCADA_ROLANTE ADD CONSTRAINT CK_ESCADA_GRUPO
    CHECK (DS_GRUPO_MANUTENCAO IN ('CRITICA_A', 'CRITICA_B', 'NAO_CRITICA_A', 'NAO_CRITICA_B'));
ALTER TABLE ESCADA_ROLANTE ADD CONSTRAINT CK_ESCADA_FABRICANTE
    CHECK (DS_FABRICANTE IN ('OTIS', 'KONE', 'SCHINDLER', 'TK_ELEVATOR', 'OUTRO'));
ALTER TABLE ESCADA_ROLANTE ADD CONSTRAINT CK_ESCADA_CONDICAO
    CHECK (ST_CONDICAO IN ('NORMAL', 'SEM_DADOS', 'ATENCAO', 'INTERVENCAO_RECOMENDADA'));
ALTER TABLE ESCADA_ROLANTE ADD CONSTRAINT CK_ESCADA_SEM_LEITURA
    CHECK (DT_ULTIMA_LEITURA IS NOT NULL OR ST_CONDICAO = 'SEM_DADOS');

COMMENT ON TABLE  ESCADA_ROLANTE                     IS 'Escada rolante monitorada. Guarda a condição atual (semáforo do dashboard) e a data da última leitura.';
COMMENT ON COLUMN ESCADA_ROLANTE.ID_ESCADA           IS 'Identificador da escada (chave primária).';
COMMENT ON COLUMN ESCADA_ROLANTE.ID_ESTACAO          IS 'Estação onde a escada está instalada (chave estrangeira).';
COMMENT ON COLUMN ESCADA_ROLANTE.CD_ESCADA           IS 'Código de negócio no padrão ECR-XXX-00, ex.: ECR-PAU-03 (Value Object CodigoEscada).';
COMMENT ON COLUMN ESCADA_ROLANTE.DS_GRUPO_MANUTENCAO IS 'Grupo de manutenção definido pelo desnível: Críticas A/B, Não críticas A/B (enum GrupoManutencao).';
COMMENT ON COLUMN ESCADA_ROLANTE.DS_FABRICANTE       IS 'Fabricante do equipamento; permite a visão multimarca (enum Fabricante).';
COMMENT ON COLUMN ESCADA_ROLANTE.DS_ACESSO           IS 'Ligação que a escada atende, ex.: Plataforma → mezanino.';
COMMENT ON COLUMN ESCADA_ROLANTE.ST_CONDICAO         IS 'Condição atual: NORMAL (verde), ATENCAO (amarelo), INTERVENCAO_RECOMENDADA (vermelho), SEM_DADOS (cinza).';
COMMENT ON COLUMN ESCADA_ROLANTE.DT_ULTIMA_LEITURA   IS 'Instante da última leitura aceita; nulo se a escada nunca enviou dados.';

