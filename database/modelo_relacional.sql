-- EQUIPE
--------------------
CREATE TABLE EQUIPE (
    ID_EQUIPE        NUMBER(10)    NOT NULL,
    ID_ESTACAO_BASE  NUMBER(10)    NOT NULL,
    NM_EQUIPE        VARCHAR2(60)  NOT NULL,
    DS_TURNO         VARCHAR2(10)  NOT NULL,
    QT_TECNICOS      NUMBER(2)     NOT NULL,
    FL_DISPONIVEL    CHAR(1)       DEFAULT 'S' NOT NULL
);

ALTER TABLE EQUIPE ADD CONSTRAINT PK_EQUIPE PRIMARY KEY (ID_EQUIPE);
ALTER TABLE EQUIPE ADD CONSTRAINT UK_EQUIPE_NOME UNIQUE (NM_EQUIPE);
ALTER TABLE EQUIPE ADD CONSTRAINT FK_EQUIPE_ESTACAO_BASE
    FOREIGN KEY (ID_ESTACAO_BASE) REFERENCES ESTACAO (ID_ESTACAO);
ALTER TABLE EQUIPE ADD CONSTRAINT CK_EQUIPE_TURNO
    CHECK (DS_TURNO IN ('MANHA', 'TARDE', 'NOITE'));
ALTER TABLE EQUIPE ADD CONSTRAINT CK_EQUIPE_TECNICOS
    CHECK (QT_TECNICOS BETWEEN 1 AND 20);
ALTER TABLE EQUIPE ADD CONSTRAINT CK_EQUIPE_DISPONIVEL
    CHECK (FL_DISPONIVEL IN ('S', 'N'));

COMMENT ON TABLE  EQUIPE                 IS 'Equipe de técnicos de manutenção que pode ser acionada por uma ordem de serviço.';
COMMENT ON COLUMN EQUIPE.ID_EQUIPE       IS 'Identificador da equipe (chave primária).';
COMMENT ON COLUMN EQUIPE.ID_ESTACAO_BASE IS 'Estação-base da equipe, ponto de partida das rotas (chave estrangeira para ESTACAO).';
COMMENT ON COLUMN EQUIPE.NM_EQUIPE       IS 'Nome único da equipe.';
COMMENT ON COLUMN EQUIPE.DS_TURNO        IS 'Turno de trabalho: MANHA, TARDE ou NOITE (enum Turno).';
COMMENT ON COLUMN EQUIPE.QT_TECNICOS     IS 'Número de técnicos, de 1 a 20.';
COMMENT ON COLUMN EQUIPE.FL_DISPONIVEL   IS 'S = livre para ser acionada; N = alocada em uma OS.';

--------------------
-- ORDEM_SERVICO
--------------------
CREATE TABLE ORDEM_SERVICO (
    ID_ORDEM_SERVICO  NUMBER(10)    NOT NULL,
    ID_ALERTA         NUMBER(12)    NOT NULL,
    ID_EQUIPE         NUMBER(10)    NOT NULL,
    ST_ORDEM_SERVICO  VARCHAR2(15)  DEFAULT 'ABERTA' NOT NULL,
    DT_ABERTURA       TIMESTAMP     NOT NULL,
    DT_INICIO         TIMESTAMP,
    DT_ENCERRAMENTO   TIMESTAMP,
    DS_DIAGNOSTICO    VARCHAR2(500)
);

ALTER TABLE ORDEM_SERVICO ADD CONSTRAINT PK_ORDEM_SERVICO PRIMARY KEY (ID_ORDEM_SERVICO);
ALTER TABLE ORDEM_SERVICO ADD CONSTRAINT UK_ORDEM_SERVICO_ALERTA UNIQUE (ID_ALERTA);
ALTER TABLE ORDEM_SERVICO ADD CONSTRAINT FK_ORDEM_SERVICO_ALERTA
    FOREIGN KEY (ID_ALERTA) REFERENCES ALERTA (ID_ALERTA);
ALTER TABLE ORDEM_SERVICO ADD CONSTRAINT FK_ORDEM_SERVICO_EQUIPE
    FOREIGN KEY (ID_EQUIPE) REFERENCES EQUIPE (ID_EQUIPE);
ALTER TABLE ORDEM_SERVICO ADD CONSTRAINT CK_ORDEM_SERVICO_STATUS
    CHECK (ST_ORDEM_SERVICO IN ('ABERTA', 'EM_ATENDIMENTO', 'CONCLUIDA', 'CANCELADA'));
ALTER TABLE ORDEM_SERVICO ADD CONSTRAINT CK_ORDEM_SERVICO_INICIO
    CHECK (DT_INICIO IS NULL OR DT_INICIO >= DT_ABERTURA);
ALTER TABLE ORDEM_SERVICO ADD CONSTRAINT CK_ORDEM_SERVICO_ENCERRAMENTO
    CHECK (DT_ENCERRAMENTO IS NULL OR DT_ENCERRAMENTO >= DT_ABERTURA);
ALTER TABLE ORDEM_SERVICO ADD CONSTRAINT CK_ORDEM_SERVICO_ENCERRADA
    CHECK (ST_ORDEM_SERVICO NOT IN ('CONCLUIDA', 'CANCELADA')
        OR (DT_ENCERRAMENTO IS NOT NULL AND DS_DIAGNOSTICO IS NOT NULL));

COMMENT ON TABLE  ORDEM_SERVICO                  IS 'Ordem de serviço que aciona uma equipe para um alerta confirmado pelo gestor.';
COMMENT ON COLUMN ORDEM_SERVICO.ID_ORDEM_SERVICO IS 'Identificador da OS (chave primária).';
COMMENT ON COLUMN ORDEM_SERVICO.ID_ALERTA        IS 'Alerta que motivou a OS (chave estrangeira, única: no máximo uma OS por alerta).';
COMMENT ON COLUMN ORDEM_SERVICO.ID_EQUIPE        IS 'Equipe acionada (chave estrangeira).';
COMMENT ON COLUMN ORDEM_SERVICO.ST_ORDEM_SERVICO IS 'ABERTA, EM_ATENDIMENTO, CONCLUIDA ou CANCELADA (enum StatusOrdemServico).';
COMMENT ON COLUMN ORDEM_SERVICO.DT_ABERTURA      IS 'Instante de abertura da OS (acionamento da equipe).';
COMMENT ON COLUMN ORDEM_SERVICO.DT_INICIO        IS 'Início do atendimento em campo.';
COMMENT ON COLUMN ORDEM_SERVICO.DT_ENCERRAMENTO  IS 'Conclusão ou cancelamento; com DT_ABERTURA, calcula o tempo de reparo (MTTR).';
COMMENT ON COLUMN ORDEM_SERVICO.DS_DIAGNOSTICO   IS 'O que o técnico encontrou e fez, ou o motivo do cancelamento.';
